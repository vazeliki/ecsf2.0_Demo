"""Build assets/ka-data.js from the ECSF Knowledge Areas workbook (Dec 2026 layout).

Usage:  python3 tools/build_ka.py ECSF_KnowledgeAreas_Dec2026.xlsx assets/ka-data.js

Reads:
  'User Guide'             the three levels (name, headline, description) and the
                           "what changes from level to level" table
  'KA Progression Levels'  KA | name | definition | level | level description
                           (the description may end with "Indicative knowledge items:" and • bullets)
  'Common Baseline'        KA | name | level  (floor level every profile needs)
  'Profile-KA Matrix'      KA | name | one column per profile (full profile name) with the target level
"""
import json, re, sys
import openpyxl

src, out = sys.argv[1], sys.argv[2]
wb = openpyxl.load_workbook(src, data_only=True)
LEVELS = ["Basic", "Applied", "Advanced"]
clean = lambda s: re.sub(r'[ \t]+', ' ', str(s)).strip() if s is not None else ""
is_ka = lambda v: isinstance(v, str) and re.fullmatch(r'K\d\d', v.strip())

# --- level definitions from the User Guide
guide = {"levels": [], "dimensions": []}
rows = [[c for c in r] for r in wb['User Guide'].iter_rows(values_only=True)]
for i, r in enumerate(rows):
    if r[0] in LEVELS and r[1] and i + 1 < len(rows):
        nxt = rows[i + 1][0] or rows[i + 1][1]          # description is on the next row (column A or B)
        guide["levels"].append({"name": r[0], "headline": clean(r[1]), "description": clean(nxt)})
    if r[0] == 'Dimension':
        for rr in rows[i + 1:]:
            if not rr[0]:
                break
            guide["dimensions"].append({"name": clean(rr[0]), **{L: clean(v) for L, v in zip(LEVELS, rr[1:4])}})
assert [l["name"] for l in guide["levels"]] == LEVELS, guide["levels"]

# --- knowledge areas and their levels
areas, cur = [], None
for r in wb['KA Progression Levels'].iter_rows(min_row=5, values_only=True):
    ka, name, definition, level, text = r[:5]
    if is_ka(ka):
        cur = {"id": ka.strip(), "name": clean(name), "definition": clean(definition), "levels": {}}
        areas.append(cur)
    if cur is None or level not in LEVELS:
        continue
    body, _, items = str(text or "").partition("Indicative knowledge items:")
    cur["levels"][level] = {
        "description": clean(body),
        "items": [clean(l.lstrip("•").strip()) for l in items.split("\n") if l.strip().startswith("•")],
    }
for a in areas:
    missing = [L for L in LEVELS if L not in a["levels"]]
    if missing:
        print("WARN", a["id"], "missing levels", missing)
ids = {a["id"] for a in areas}

# --- common baseline
baseline = []
for r in wb['Common Baseline'].iter_rows(min_row=5, values_only=True):
    if is_ka(r[0]):
        assert r[0] in ids and r[2] in LEVELS, r
        baseline.append({"id": r[0].strip(), "level": r[2]})

# --- profile x KA target levels (profiles keyed by their full name, as in data.js)
ws = wb['Profile-KA Matrix']
rows = list(ws.iter_rows(values_only=True))
hdr = next(i for i, r in enumerate(rows) if r[0] == 'KA')
names = [clean(n) for n in rows[hdr][2:] if n]
profiles = {n: [] for n in names}
for r in rows[hdr + 1:]:
    if not is_ka(r[0]):
        continue
    assert r[0] in ids, r[0]
    for n, v in zip(names, r[2:2 + len(names)]):
        if v in LEVELS:
            profiles[n].append({"id": r[0].strip(), "level": v})
        elif v not in (None, "", "-"):
            print("WARN value", r[0], n, v)

data = {"source": src.split('/')[-1], "levels": LEVELS, "guide": guide,
        "areas": areas, "baseline": baseline, "profiles": profiles}
with open(out, 'w') as f:
    f.write("// Generated by tools/build_ka.py from the ECSF Knowledge Areas workbook.\n")
    f.write("window.ECSF_KA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
unused = [a["id"] for a in areas if not any(m["id"] == a["id"] for v in profiles.values() for m in v)]
print(len(areas), "KAs |", sum(len(l["items"]) for a in areas for l in a["levels"].values()), "indicative items |",
      len(baseline), "baseline |", {n.split(' (')[0][:22]: len(v) for n, v in profiles.items()},
      "| KAs with no profile:", unused)
